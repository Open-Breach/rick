//! The `rick` command (specs/system-integration.md §7.1): a symbolic link
//! in the scope's bin directory, `~/.local/bin/rick`, and the shell
//! function in Rick's `path.sh` — the file the installer plugin has the
//! login shells source — which puts `rick` on the PATH of a login shell
//! that does not read `~/.local/bin`.

use std::fs;
use std::path::{Path, PathBuf};

use super::{BINARY, LinuxEnv, is_foreign, same_file};
use crate::integration::{Actual, Check, Receipt};

/// Where the link goes: `~/.local/bin/rick`.
pub(super) fn link_path(env: &LinuxEnv) -> PathBuf {
    env.home.join(".local/bin").join(BINARY)
}

/// Rick's managed PATH file, `<config home>/rick/path.sh`.
pub(super) fn path_file(env: &LinuxEnv) -> PathBuf {
    env.config_home.join("rick/path.sh")
}

/// Whether `text`, a `path.sh`, defines the `rick` function for `binary`.
pub(super) fn defines_function(text: &str, binary: &Path) -> bool {
    let binary = binary.to_string_lossy();
    text.lines().any(|line| {
        let line = line.trim_start();
        line.starts_with("rick()") && line.contains(&*binary)
    })
}

/// The command is set up when the link points at `binary` and `path.sh`
/// defines the function for it. Something else under the link's name is
/// in the way unless the receipt says Rick wrote it.
pub(super) fn check(env: &LinuxEnv, binary: &Path, receipt: &Receipt) -> Check {
    let link = link_path(env);
    let mut check = Check {
        actual: Actual::Missing,
        place: Some(link.clone()),
        target: Some(binary.to_path_buf()),
        ..Check::default()
    };
    let linked =
        fs::read_link(&link).is_ok_and(|target| target == binary || same_file(&link, binary));
    if !linked && is_foreign(env, &link, receipt) {
        check.foreign.push(link);
    }
    let function =
        fs::read_to_string(path_file(env)).is_ok_and(|text| defines_function(&text, binary));
    if linked && function {
        check.actual = Actual::SetUp;
    }
    check
}

#[cfg(test)]
mod tests {
    use super::super::tests::{Home, write};
    use super::*;
    use crate::integration::{Integration as _, Item, Request};

    #[test]
    fn the_link_and_the_shell_function_make_the_command() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        let request = Request::default();
        let link = link_path(&home.env);
        let found = integration.check_integration(Item::RickCommand, &request);
        assert_eq!(found.actual, Actual::Missing);
        assert_eq!(found.place, Some(link.clone()));
        assert_eq!(found.target, Some(home.env.exe.clone()));

        fs::create_dir_all(link.parent().unwrap_or(&link)).unwrap_or_else(|e| panic!("{e}"));
        std::os::unix::fs::symlink(&home.env.exe, &link).unwrap_or_else(|e| panic!("{e}"));
        // The link alone is half of it.
        let found = integration.check_integration(Item::RickCommand, &request);
        assert_eq!(found.actual, Actual::Missing);
        assert!(found.foreign.is_empty());
        write(
            &path_file(&home.env),
            &format!(
                "# Generated by Rick\nrick() {{ \"{}\" \"$@\"; }}\n",
                home.env.exe.display()
            ),
        );
        let found = integration.check_integration(Item::RickCommand, &request);
        assert_eq!(found.actual, Actual::SetUp);
    }

    #[test]
    fn a_link_to_another_rick_is_in_the_way() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        let link = link_path(&home.env);
        fs::create_dir_all(link.parent().unwrap_or(&link)).unwrap_or_else(|e| panic!("{e}"));
        std::os::unix::fs::symlink("/opt/other/rick", &link).unwrap_or_else(|e| panic!("{e}"));
        let found = integration.check_integration(Item::RickCommand, &Request::default());
        assert_eq!(found.actual, Actual::Missing);
        assert_eq!(found.foreign, std::slice::from_ref(&link));
        let request = Request {
            receipt: Receipt {
                files: vec![home.env.tilde(&link)],
                ..Receipt::default()
            },
            ..Request::default()
        };
        let found = integration.check_integration(Item::RickCommand, &request);
        assert!(found.foreign.is_empty(), "Rick's own stale link");
    }
}
