//! The `rick` command (specs/system-integration.md §7.1): a symbolic link
//! in the scope's bin directory, `~/.local/bin/rick`, and the shell
//! function in Rick's `path.sh` — the file the installer plugin has the
//! login shells source — which puts `rick` on the PATH of a login shell
//! that does not read `~/.local/bin`.

use std::fs;
use std::path::{Path, PathBuf};

use types::Error;

use super::{BINARY, LinuxEnv, is_foreign, record, refuse_foreign, remove, same_file, write_file};
use crate::integration::{Actual, COMMAND_BLOCK, Check, Receipt, Request, without_command_block};

/// The first line of a `path.sh` or a fish drop-in Rick creates, the one
/// the installer plugin writes too.
const HEADER: &str = "# Generated by Rick from its install records; edit nothing here.\n";
/// The marker of the line that has a login shell source `path.sh`, the
/// installer plugin's.
const PROFILE_MARK: &str = "# added by rick";
/// What the block says the function is for.
const WHY: &str = "# `rick` for a login shell without ~/.local/bin on its PATH: no argument opens the shell's directory.";

/// Where the link goes: `~/.local/bin/rick`.
pub(super) fn link_path(env: &LinuxEnv) -> PathBuf {
    env.home.join(".local/bin").join(BINARY)
}

/// Rick's managed PATH file, `<config home>/rick/path.sh`.
pub(super) fn path_file(env: &LinuxEnv) -> PathBuf {
    env.config_home.join("rick/path.sh")
}

/// Whether `text`, a `path.sh`, defines the `rick` function for `binary`.
pub(super) fn defines_function(text: &str, binary: &Path) -> bool {
    let binary = binary.to_string_lossy();
    text.lines().any(|line| {
        let line = line.trim_start();
        line.starts_with("rick()") && line.contains(&*binary)
    })
}

/// The command is set up when the link points at `binary` and `path.sh`
/// defines the function for it. Something else under the link's name is
/// in the way unless the receipt says Rick wrote it.
pub(super) fn check(env: &LinuxEnv, binary: &Path, receipt: &Receipt) -> Check {
    let link = link_path(env);
    let mut check = Check {
        actual: Actual::Missing,
        place: Some(link.clone()),
        target: Some(binary.to_path_buf()),
        ..Check::default()
    };
    let linked =
        fs::read_link(&link).is_ok_and(|target| target == binary || same_file(&link, binary));
    if !linked && is_foreign(env, &link, receipt) {
        check.foreign.push(link);
    }
    let function =
        fs::read_to_string(path_file(env)).is_ok_and(|text| defines_function(&text, binary));
    if linked && function {
        check.actual = Actual::SetUp;
    }
    check
}

/// The fish drop-in beside `path.sh`, written where fish is configured.
fn fish_file(env: &LinuxEnv) -> PathBuf {
    env.config_home.join("fish/conf.d/rick.fish")
}

/// The login shells' profiles that source `path.sh`, and whether Rick
/// creates one that is not there: `~/.profile` yes, `~/.zprofile` only
/// when zsh has one.
fn profiles(env: &LinuxEnv) -> [(PathBuf, bool); 2] {
    [
        (env.home.join(".profile"), true),
        (env.home.join(".zprofile"), false),
    ]
}

/// A path inside double quotes of a shell line.
fn shell_quoted(path: &Path) -> String {
    let mut out = String::new();
    for c in path.to_string_lossy().chars() {
        if matches!(c, '"' | '\\' | '$' | '`') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// The block for `path.sh`: the function between its marker lines.
fn sh_block(binary: &Path) -> String {
    format!(
        "{}\n{WHY}\nrick() {{ \"{}\" \"$@\"; }}\n{}\n",
        COMMAND_BLOCK.0,
        shell_quoted(binary),
        COMMAND_BLOCK.1
    )
}

/// The block for the fish drop-in.
fn fish_block(binary: &Path) -> String {
    format!(
        "{}\n{WHY}\nfunction rick\n    \"{}\" $argv\nend\n{}\n",
        COMMAND_BLOCK.0,
        shell_quoted(binary),
        COMMAND_BLOCK.1
    )
}

/// Whether a managed file says anything besides comments: a PATH entry of
/// the installer's, a function.
fn has_content(text: &str) -> bool {
    text.lines().any(|line| {
        let line = line.trim();
        !line.is_empty() && !line.starts_with('#')
    })
}

/// Puts `block` into the managed file at `path`, in place of an older
/// block, creating the file with its header when there is none; `skip`
/// says the rest of the file already does what the block would. The file
/// is recorded when it was created.
fn write_block(
    env: &LinuxEnv,
    path: &Path,
    block: &str,
    skip: impl Fn(&str) -> bool,
    receipt: &mut Receipt,
) -> Result<(), Error> {
    let existing = fs::read_to_string(path).ok();
    let text = existing.clone().unwrap_or_else(|| HEADER.to_owned());
    let mut out = without_command_block(&text);
    if !skip(&out) {
        if !out.is_empty() && !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(block);
    }
    if existing.as_deref() != Some(out.as_str()) {
        write_file(path, out.as_bytes())?;
    }
    if existing.is_none() {
        record(env, receipt, path);
    }
    Ok(())
}

/// Takes Rick's block out of the managed file at `path`; a file that says
/// nothing afterwards goes. Returns whether the file is gone.
fn remove_block(path: &Path) -> Result<bool, Error> {
    let Ok(text) = fs::read_to_string(path) else {
        return Ok(true);
    };
    let out = without_command_block(&text);
    if !has_content(&out) {
        remove(path)?;
        return Ok(true);
    }
    if out != text {
        write_file(path, out.as_bytes())?;
    }
    Ok(false)
}

/// Makes the link and the shell function: the link in `~/.local/bin`
/// (replaced when it is Rick's own or the request says so), the function
/// as a marked block in `path.sh` and, where fish is configured, in its
/// drop-in, and the line that has the login shells source `path.sh`.
pub(super) fn perform(env: &LinuxEnv, binary: &Path, request: &Request) -> Result<Receipt, Error> {
    refuse_foreign(&check(env, binary, &request.receipt), request)?;
    let mut receipt = request.receipt.clone();
    let link = link_path(env);
    let linked =
        fs::read_link(&link).is_ok_and(|target| target == binary || same_file(&link, binary));
    if !linked {
        let parent = link.parent().unwrap_or(Path::new("."));
        fs::create_dir_all(parent).map_err(Error::from_io)?;
        // A link under a temporary name renamed over the old one: there
        // is no moment without a `rick`.
        let tmp = parent.join(format!(".{BINARY}.tmp-{}", std::process::id()));
        let _ = fs::remove_file(&tmp);
        std::os::unix::fs::symlink(binary, &tmp).map_err(Error::from_io)?;
        fs::rename(&tmp, &link).map_err(|error| {
            let _ = fs::remove_file(&tmp);
            Error::from_io(error)
        })?;
        record(env, &mut receipt, &link);
    }
    let file = path_file(env);
    write_block(
        env,
        &file,
        &sh_block(binary),
        |rest| defines_function(rest, binary),
        &mut receipt,
    )?;
    if env.config_home.join("fish").is_dir() {
        write_block(
            env,
            &fish_file(env),
            &fish_block(binary),
            |_| false,
            &mut receipt,
        )?;
    }
    let source = format!(
        "[ -f \"{0}\" ] && . \"{0}\" {PROFILE_MARK}",
        file.to_string_lossy()
    );
    for (profile, create) in profiles(env) {
        let text = match fs::read_to_string(&profile) {
            Ok(text) => text,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound && create => String::new(),
            Err(_) => continue,
        };
        if text.lines().any(|l| l.contains(PROFILE_MARK)) {
            continue;
        }
        let mut out = text;
        if !out.is_empty() && !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(&source);
        out.push('\n');
        fs::write(&profile, out).map_err(Error::from_io)?;
        // The line was not there before: an undo may take it out again.
        receipt.previous.insert(env.tilde(&profile), String::new());
    }
    Ok(receipt)
}

/// Removes the link the receipt lists, Rick's block from `path.sh` and the
/// fish drop-in, and, once `path.sh` is gone because nothing else needed
/// it, the line Rick added to the profiles.
pub(super) fn undo(env: &LinuxEnv, receipt: &Receipt) -> Result<(), Error> {
    let link = link_path(env);
    if receipt.files.contains(&env.tilde(&link))
        && fs::symlink_metadata(&link).is_ok_and(|meta| meta.is_symlink())
    {
        remove(&link)?;
    }
    remove_block(&fish_file(env))?;
    if !remove_block(&path_file(env))? {
        // The installer's PATH entries still need the file sourced.
        return Ok(());
    }
    for (profile, _) in profiles(env) {
        if !receipt.previous.contains_key(&env.tilde(&profile)) {
            continue;
        }
        let Ok(text) = fs::read_to_string(&profile) else {
            continue;
        };
        let kept: Vec<&str> = text.lines().filter(|l| !l.contains(PROFILE_MARK)).collect();
        if kept.iter().all(|l| l.trim().is_empty()) {
            // Rick's line was all the file held, so Rick made the file.
            remove(&profile)?;
        } else {
            fs::write(&profile, kept.join("\n") + "\n").map_err(Error::from_io)?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::super::tests::{Home, write};
    use super::*;
    use crate::integration::{Integration as _, Item, Request};

    #[test]
    fn the_link_and_the_shell_function_make_the_command() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        let request = Request::default();
        let link = link_path(&home.env);
        let found = integration.check_integration(Item::RickCommand, &request);
        assert_eq!(found.actual, Actual::Missing);
        assert_eq!(found.place, Some(link.clone()));
        assert_eq!(found.target, Some(home.env.exe.clone()));

        fs::create_dir_all(link.parent().unwrap_or(&link)).unwrap_or_else(|e| panic!("{e}"));
        std::os::unix::fs::symlink(&home.env.exe, &link).unwrap_or_else(|e| panic!("{e}"));
        // The link alone is half of it.
        let found = integration.check_integration(Item::RickCommand, &request);
        assert_eq!(found.actual, Actual::Missing);
        assert_eq!(found.foreign, [] as [PathBuf; 0]);
        write(
            &path_file(&home.env),
            &format!(
                "# Generated by Rick\nrick() {{ \"{}\" \"$@\"; }}\n",
                home.env.exe.display()
            ),
        );
        let found = integration.check_integration(Item::RickCommand, &request);
        assert_eq!(found.actual, Actual::SetUp);
    }

    #[test]
    fn a_link_to_another_rick_is_in_the_way() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        let link = link_path(&home.env);
        fs::create_dir_all(link.parent().unwrap_or(&link)).unwrap_or_else(|e| panic!("{e}"));
        std::os::unix::fs::symlink("/opt/other/rick", &link).unwrap_or_else(|e| panic!("{e}"));
        let found = integration.check_integration(Item::RickCommand, &Request::default());
        assert_eq!(found.actual, Actual::Missing);
        assert_eq!(found.foreign, std::slice::from_ref(&link));
        let request = Request {
            receipt: Receipt {
                files: vec![home.env.tilde(&link)],
                ..Receipt::default()
            },
            ..Request::default()
        };
        let found = integration.check_integration(Item::RickCommand, &request);
        assert!(found.foreign.is_empty(), "Rick's own stale link");
    }

    #[test]
    fn performing_links_defines_the_function_and_has_the_profile_source_it() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        let receipt = integration
            .perform_integration(Item::RickCommand, &Request::default())
            .unwrap_or_else(|e| panic!("{e}"));
        let link = link_path(&home.env);
        assert_eq!(fs::read_link(&link).ok(), Some(home.env.exe.clone()));
        let file = path_file(&home.env);
        let text = fs::read_to_string(&file).unwrap_or_else(|e| panic!("{e}"));
        assert!(text.starts_with("# Generated by Rick"), "{text}");
        assert!(
            text.contains(&format!(
                "rick() {{ \"{}\" \"$@\"; }}",
                home.env.exe.display()
            )),
            "{text}"
        );
        assert!(crate::integration::command_block(&text).is_some());
        let profile = fs::read_to_string(home.env.home.join(".profile")).unwrap_or_default();
        assert_eq!(
            profile,
            format!(
                "[ -f \"{0}\" ] && . \"{0}\" # added by rick\n",
                file.display()
            )
        );
        assert!(
            !home.env.home.join(".zprofile").exists(),
            "zsh is not in use"
        );
        assert!(!fish_file(&home.env).exists(), "fish is not configured");
        assert_eq!(
            receipt.files,
            ["~/.local/bin/rick", "~/.config/rick/path.sh"]
        );
        assert!(receipt.previous.contains_key("~/.profile"));
        let request = Request {
            receipt: receipt.clone(),
            ..Request::default()
        };
        assert_eq!(
            integration
                .check_integration(Item::RickCommand, &request)
                .actual,
            Actual::SetUp
        );
        let again = integration
            .perform_integration(Item::RickCommand, &request)
            .unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(again, receipt, "nothing more to write");
        assert_eq!(
            fs::read_to_string(home.env.home.join(".profile")).unwrap_or_default(),
            profile,
            "the line is added once"
        );

        integration
            .undo_integration(Item::RickCommand, &request)
            .unwrap_or_else(|e| panic!("{e}"));
        assert!(fs::symlink_metadata(&link).is_err());
        assert!(!file.exists());
        assert!(!home.env.home.join(".profile").exists());
    }

    #[test]
    fn the_installers_lines_and_the_users_profile_survive_the_undo() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        // A toolchain the installer put on the PATH, a profile of the
        // user's own with the installer's line, zsh and fish in use.
        let file = path_file(&home.env);
        let installers = "# Generated by Rick from its install records; edit nothing here.\nexport PATH=\"/home/u/.local/opt/jdk/current/bin:$PATH\"\n";
        write(&file, installers);
        let profile = home.env.home.join(".profile");
        let users = format!(
            "export EDITOR=vi\n[ -f \"{0}\" ] && . \"{0}\" # added by rick\n",
            file.display()
        );
        write(&profile, &users);
        write(&home.env.home.join(".zprofile"), "# zsh\n");
        fs::create_dir_all(home.env.config_home.join("fish")).unwrap_or_else(|e| panic!("{e}"));

        let receipt = integration
            .perform_integration(Item::RickCommand, &Request::default())
            .unwrap_or_else(|e| panic!("{e}"));
        let text = fs::read_to_string(&file).unwrap_or_default();
        assert!(text.starts_with(installers), "{text}");
        assert!(crate::integration::command_block(&text).is_some());
        assert_eq!(fs::read_to_string(&profile).unwrap_or_default(), users);
        assert!(
            fs::read_to_string(home.env.home.join(".zprofile"))
                .unwrap_or_default()
                .contains("# added by rick")
        );
        let fish = fs::read_to_string(fish_file(&home.env)).unwrap_or_default();
        assert!(fish.contains("function rick\n"), "{fish}");
        assert!(
            !receipt.files.contains(&home.env.tilde(&file)),
            "path.sh was the installer's"
        );
        assert!(!receipt.previous.contains_key("~/.profile"));
        assert!(receipt.previous.contains_key("~/.zprofile"));

        let request = Request {
            receipt,
            ..Request::default()
        };
        integration
            .undo_integration(Item::RickCommand, &request)
            .unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(fs::read_to_string(&file).unwrap_or_default(), installers);
        assert_eq!(fs::read_to_string(&profile).unwrap_or_default(), users);
        assert!(!fish_file(&home.env).exists());
        // path.sh is still needed, so every profile keeps sourcing it.
        assert!(
            fs::read_to_string(home.env.home.join(".zprofile"))
                .unwrap_or_default()
                .contains("# added by rick")
        );
    }

    #[test]
    fn a_function_the_installer_defined_is_not_defined_twice() {
        let home = Home::new("GNOME");
        let file = path_file(&home.env);
        let installers = format!(
            "# Generated by Rick from its install records; edit nothing here.\nrick() {{ \"{}\" \"$@\"; }}\n",
            home.env.exe.display()
        );
        write(&file, &installers);
        home.integration()
            .perform_integration(Item::RickCommand, &Request::default())
            .unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(fs::read_to_string(&file).unwrap_or_default(), installers);
    }

    #[test]
    fn a_foreign_link_is_replaced_only_on_request_and_a_stale_one_of_ricks_always() {
        let home = Home::new("GNOME");
        let integration = home.integration();
        let link = link_path(&home.env);
        fs::create_dir_all(link.parent().unwrap_or(&link)).unwrap_or_else(|e| panic!("{e}"));
        std::os::unix::fs::symlink("/opt/other/rick", &link).unwrap_or_else(|e| panic!("{e}"));
        let refused = integration.perform_integration(Item::RickCommand, &Request::default());
        assert!(
            matches!(&refused, Err(Error::Io(e)) if e.kind() == std::io::ErrorKind::AlreadyExists),
            "{refused:?}"
        );
        assert_eq!(
            fs::read_link(&link).ok().as_deref(),
            Some(Path::new("/opt/other/rick"))
        );
        assert!(!path_file(&home.env).exists(), "nothing was written");
        // Rick's own link, pointing at where Rick used to be: just moved.
        let stale = Request {
            receipt: Receipt {
                files: vec![home.env.tilde(&link)],
                ..Receipt::default()
            },
            ..Request::default()
        };
        integration
            .perform_integration(Item::RickCommand, &stale)
            .unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(fs::read_link(&link).ok(), Some(home.env.exe.clone()));
        // And the foreign one once the user agreed.
        fs::remove_file(&link).unwrap_or_else(|e| panic!("{e}"));
        std::os::unix::fs::symlink("/opt/other/rick", &link).unwrap_or_else(|e| panic!("{e}"));
        let receipt = integration
            .perform_integration(
                Item::RickCommand,
                &Request {
                    replace: true,
                    ..Request::default()
                },
            )
            .unwrap_or_else(|e| panic!("{e}"));
        assert_eq!(fs::read_link(&link).ok(), Some(home.env.exe.clone()));
        assert!(receipt.files.contains(&home.env.tilde(&link)));
    }
}
